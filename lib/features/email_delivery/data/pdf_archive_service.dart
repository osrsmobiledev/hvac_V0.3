/// Result of a PDF archive attempt.
class PdfArchiveResult {
  final bool isSuccess;

  /// Absolute path to the archived PDF file; empty on failure.
  final String archivePath;
  final String? errorMessage;

  const PdfArchiveResult({
    required this.isSuccess,
    required this.archivePath,
    this.errorMessage,
  });
}

/// Safely archives the frozen certificate PDF for a finalized visit.
///
/// Follows the write-then-verify-then-rename pattern specified in the
/// MASTER_EMAIL_DELIVERY_WORKFLOW.md:
///   1. Generate PDF bytes from the frozen snapshot_json.
///   2. Write to `certificates/staging/visit_<id>_<attest>_v<micros>_<seq>.tmp` with flush.
///   3. Verify written file length equals generated byte count.
///   4. Rename (atomic on same filesystem) to `certificates/...pdf`.
///
/// Concurrent archive calls and cleanup are serialized via [_lock].
abstract final class PdfArchiveService {
  /// Application-level lock to serialize concurrent archive operations and cleanup.
  static final Lock _lock = Lock();

  /// Sequence counter for sub-microsecond collision avoidance.
  static int _sequence = 0;

  /// Cleans up orphaned temporary `.tmp` staging files left by interrupted runs.
  ///
  /// Serialized under [_lock] to prevent deleting any file actively being written.
  /// Call this once at app startup before the app becomes interactive.
  static Future<void> cleanupStagingFiles({
    Directory? documentsDirectoryOverride,
  }) async {
    return _lock.synchronized(() async {
      try {
        final docsDir = documentsDirectoryOverride ??
            await getApplicationDocumentsDirectory();
        final stagingDir =
            Directory(p.join(docsDir.path, 'certificates', 'staging'));
        if (!await stagingDir.exists()) return;
        await for (final entry in stagingDir.list()) {
          if (entry is File && entry.path.endsWith('.tmp')) {
            try {
              await entry.delete();
              debugPrint(
                  '[PdfArchiveService] Deleted orphaned staging file: ${entry.path}');
            } catch (e) {
              debugPrint(
                  '[PdfArchiveService] Could not delete staging file: $e');
            }
          }
        }
      } catch (e) {
        debugPrint('[PdfArchiveService] cleanupStagingFiles error: $e');
      }
    });
  }

  /// Safely deletes an unregistered archive file if database registration fails
  /// and the technician cancels or skips registration.
  ///
  /// Strictly verifies that [path] resides directly within the app's `certificates/`
  /// directory and ends with `.pdf` to prevent deleting unrelated files.
  /// Uses asynchronous Dart file APIs and serializes under [_lock].
  static Future<bool> deleteUnregisteredArchiveFile(
    String path, {
    Directory? documentsDirectoryOverride,
  }) async {
    if (path.isEmpty) return false;
    return _lock.synchronized(() async {
      try {
        final docsDir = documentsDirectoryOverride ??
            await getApplicationDocumentsDirectory();
        final certDirPath = p.normalize(p.join(docsDir.path, 'certificates'));
        final normalizedPath = p.normalize(path);

        final parentDir = p.normalize(p.dirname(normalizedPath));
        if (parentDir != certDirPath || !normalizedPath.endsWith('.pdf')) {
          debugPrint(
              '[PdfArchiveService] Refusing to delete non-certificate path: $path');
          return false;
        }

        final file = File(normalizedPath);
        if (await file.exists()) {
          await file.delete();
          debugPrint(
              '[PdfArchiveService] Deleted unregistered archive file: $normalizedPath');
          return true;
        }
        return false;
      } catch (e) {
        debugPrint(
            '[PdfArchiveService] deleteUnregisteredArchiveFile error: $e');
        return false;
      }
    });
  }

  /// Archives the PDF certificate for [visitId] using its frozen [snapshotJson].
  static Future<PdfArchiveResult> archiveCertificate({
    required int visitId,
    required String snapshotJson,
    Directory? documentsDirectoryOverride,
  }) async {
    return _lock.synchronized(() async {
      try {
        return await _doArchive(
          visitId: visitId,
          snapshotJson: snapshotJson,
          documentsDirectoryOverride: documentsDirectoryOverride,
        );
      } catch (e, stack) {
        debugPrint('[PdfArchiveService] archiveCertificate error: $e\n$stack');
        return PdfArchiveResult(
          isSuccess: false,
          archivePath: '',
          errorMessage: e.toString(),
        );
      }
    });
  }

  static Future<PdfArchiveResult> _doArchive({
    required int visitId,
    required String snapshotJson,
    Directory? documentsDirectoryOverride,
  }) async {
    // 1. Decode frozen snapshot and generate PDF bytes from it.
    final snapshot = jsonDecode(snapshotJson) as Map<String, Object?>;
    final PdfVisitData visitData = PdfVisitLoader.fromSnapshot(snapshot);
    final Uint8List pdfBytes =
        await CombustionPdfGenerator.generateCertificate(visitData);

    // 2. Ensure certificates/ and certificates/staging/ directories exist.
    final docsDir =
        documentsDirectoryOverride ?? await getApplicationDocumentsDirectory();
    final certDir = Directory(p.join(docsDir.path, 'certificates'));
    final stagingDir =
        Directory(p.join(docsDir.path, 'certificates', 'staging'));
    await certDir.create(recursive: true);
    await stagingDir.create(recursive: true);

    // 3. Generate collision-resistant names with microseconds & sequence.
    final micros = DateTime.now().microsecondsSinceEpoch;
    final seq = ++_sequence;
    final sanitized = _sanitizeAttest(visitData.volgnummerAttest);

    final stagingName = 'visit_${visitId}_${sanitized}_v${micros}_$seq.tmp';
    final archiveName = 'visit_${visitId}_${sanitized}_v${micros}_$seq.pdf';

    final stagingPath = p.join(stagingDir.path, stagingName);
    final archivePath = p.join(certDir.path, archiveName);

    // 4. Write to staging with flush, then verify byte count.
    final stagingFile = File(stagingPath);
    await stagingFile.writeAsBytes(pdfBytes, flush: true);

    final writtenLength = await stagingFile.length();
    if (writtenLength != pdfBytes.length) {
      await stagingFile.delete().catchError((_) => stagingFile);
      throw StateError(
        'PDF archive length mismatch: wrote $writtenLength, '
        'expected ${pdfBytes.length} bytes.',
      );
    }

    // 5. Rename to final archive path (atomic on same filesystem).
    await stagingFile.rename(archivePath);

    debugPrint('[PdfArchiveService] Archived certificate: $archivePath');
    return PdfArchiveResult(isSuccess: true, archivePath: archivePath);
  }

  /// Sanitizes an attest number for filesystem use.
  static String _sanitizeAttest(String attestNumber) {
    final trimmed = attestNumber.trim();
    if (trimmed.isEmpty) return 'concept';
    return trimmed.replaceAll(RegExp(r'[\\/:*?"<>| ]'), '_');
  }
}
